  /* ---------- runtime ---------- */
  var current = 'et';

  function t(key, vars, lang) {
    var L = STR[lang || current] || STR.et;
    var s = L[key];
    if (s === undefined) s = STR.en[key];
    if (s === undefined) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] !== undefined ? vars[k] : m; });
    return s;
  }

  function setLang(lang) {
    if (!STR[lang]) lang = 'et';
    current = lang;
    document.documentElement.lang = lang;
  }

  function applyStatic(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    root.querySelectorAll('[data-i18n-ph]').forEach(function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
    root.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var s = t(el.getAttribute('data-i18n-title'));
      el.setAttribute('title', s); el.setAttribute('aria-label', s);
    });
    document.title = t('app.title') + ' 🌹';
  }

  function capitalizeName(name) {
    return String(name || '').trim().replace(/\s+/g, ' ').split(' ').map(function (w) {
      return w.charAt(0).toLocaleUpperCase() + w.slice(1);
    }).join(' ');
  }

  window.I18N = {
    STR: STR, TOPICS: TOPICS, SUBJECT_IDS: SUBJECT_IDS, LOADING: LOADING, THEMES: THEMES, OUT: OUT,
    KEY_LINKS: KEY_LINKS, TUT: TUT,
    t: t, setLang: setLang, applyStatic: applyStatic, capitalizeName: capitalizeName,
    get lang() { return current; }
  };
